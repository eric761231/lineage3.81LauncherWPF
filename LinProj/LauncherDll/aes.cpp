void aes_encrypt(unsigned char* key, unsigned char* buffer, int len)
{
    // 使用 Windows BCrypt 做 AES-128-ECB 加密
    bcrypt_aes_ecb(key, buffer, len, true);
}

void aes_decrypt(unsigned char* key, unsigned char* buffer, int len)
{
    // 使用 Windows BCrypt 做 AES-128-ECB 解密
    bcrypt_aes_ecb(key, buffer, len, false);
}

void config_decrypt(unsigned char* key, unsigned char* buffer, int len)
{
	// AES 只能處理 16 倍數長度的區塊；剩餘不足 16 bytes 的部分只做 XOR
	// 注意：與 C# CryptoService.ConfigDecrypt() 邏輯完全對應
	int aesLen = (len / 16) * 16;

	// 先做 AES 解密（對應 C# 先 AES 再 XOR 的解密順序）
	if (aesLen > 0)
		aes_decrypt(key, buffer, aesLen);

	// 再對所有位元組做 XOR 還原（包含 AES 無法處理的尾部剩餘位元組）
	unsigned char xorTable[256];
	memcpy(xorTable, XorTableBase, 256);
	for (int i = 0; i < 256; i++) {
		xorTable[i] ^= key[i % 16];
	}

	for (int i = 0; i < len; i++) {
		buffer[i] ^= xorTable[i % 256];
	}
}

void config_encrypt(unsigned char* key, unsigned char* buffer, int len)
{
	// 先對所有位元組做 XOR 加密（包含尾部不足 16 bytes 的區塊）
	// 注意：與 C# CryptoService.ConfigEncrypt() 邏輯完全對應
	unsigned char xorTable[256];
	memcpy(xorTable, XorTableBase, 256);
	for (int i = 0; i < 256; i++) {
		xorTable[i] ^= key[i % 16];
	}

	for (int i = 0; i < len; i++) {
		buffer[i] ^= xorTable[i % 256];
	}

	// 再做 AES 加密（只處理 16 倍數長度的整數區塊）
	int aesLen = (len / 16) * 16;
	if (aesLen > 0)
		aes_encrypt(key, buffer, aesLen);
}

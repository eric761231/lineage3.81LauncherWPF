// Windows BCrypt AES-128-ECB：一次處理 len 個位元組（len 必須為 16 的倍數）
static void bcrypt_aes_ecb(unsigned char* key, unsigned char* buffer, int len, bool encrypt)
{
    BCRYPT_ALG_HANDLE hAlg  = NULL;
    BCRYPT_KEY_HANDLE hKey  = NULL;
    ULONG cbKeyObj = 0, cbData = 0, cbResult = 0;

    BCryptOpenAlgorithmProvider(&hAlg, BCRYPT_AES_ALGORITHM, NULL, 0);
    // 設定為 ECB 模式（無 IV）
    BCryptSetProperty(hAlg, BCRYPT_CHAINING_MODE,
                      (PBYTE)BCRYPT_CHAIN_MODE_ECB,
                      sizeof(BCRYPT_CHAIN_MODE_ECB), 0);
    // 取得 key object 所需大小
    BCryptGetProperty(hAlg, BCRYPT_OBJECT_LENGTH,
                      (PBYTE)&cbKeyObj, sizeof(ULONG), &cbData, 0);
    PBYTE pbKeyObj = (PBYTE)LocalAlloc(LMEM_ZEROINIT, cbKeyObj);
    // 匯入 16-byte (128-bit) 金鑰
    BCryptGenerateSymmetricKey(hAlg, &hKey, pbKeyObj, cbKeyObj, key, 16, 0);

    if (encrypt)
        BCryptEncrypt(hKey, buffer, (ULONG)len, NULL, NULL, 0, buffer, (ULONG)len, &cbResult, 0);
    else
        BCryptDecrypt(hKey, buffer, (ULONG)len, NULL, NULL, 0, buffer, (ULONG)len, &cbResult, 0);

    BCryptDestroyKey(hKey);
    LocalFree(pbKeyObj);
    BCryptCloseAlgorithmProvider(hAlg, 0);
}


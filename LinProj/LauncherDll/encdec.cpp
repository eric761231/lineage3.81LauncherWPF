// encdec_init: 從 LinGate.ini 讀取 encrypt_key，建立執行期 XOR 查表
// 供首次進入伺服器前的靜態設定路線呼叫
void encdec_init()
{
    VMProtectBegin;
    // 從 INI 讀取金鑰（最多 32 bytes，只取前 16 bytes 做 XOR）
    GetPrivateProfileStringA("main", "encrypt_key", "", (char*)encdec_key, 32, "./LinGate.ini");
    memcpy(init_key, encdec_key, 16);
    for (int i = 0; i < 256; i++) {
        xor_table[i] = xor_base[i] ^ encdec_key[i % 16];
    }
    VMProtectEnd;
}

// encdec_init_key: 直接傳入 16 byte 金鑰（由 LauncherDll 從共享記憶體取得後呼叫）
// 參數 key 不可命名為 encdec_key，否則會遮蔽全域變數
void encdec_init_key(unsigned char* key)
{
    VMProtectBegin;
    memcpy(init_key, key, 16);
    for (int i = 0; i < 256; i++) {
        xor_table[i] = xor_base[i] ^ key[i % 16];
    }
    VMProtectEnd;
}

// encdec_encrypt: 封包加密 —— 對每個位元組 XOR init_key[i % 16]
// AES 路徑已停用（參見 C# CryptoService.cs 之 UseAES 旗標）
void encdec_encrypt(const unsigned char* src, unsigned char* dst, int len)
{
    VMProtectBegin;
    for (int i = 0; i < len; i++) {
        dst[i] = src[i] ^ init_key[i % 16];
    }
    VMProtectEnd;
}

// encdec_decrypt: 封包解密 —— XOR 為對稱運算，直接還原
void encdec_decrypt(const unsigned char* src, unsigned char* dst, int len)
{
    VMProtectBegin;
    memcpy(dst, src, len);
    for (int i = 0; i < len; i++) {
        dst[i] ^= init_key[i % 16];
    }
    VMProtectEnd;
}